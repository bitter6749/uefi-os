#ifndef HEAP_H
#define HEAP_H

#include "memory.h"

// ====================================================================================
// メモリ管理用の定数定義
// ====================================================================================
#define ALIGNMENT             8ULL                // 8バイトアライメント
#define ALIGN_MASK            (ALIGNMENT - 1)     // アライメント計算用マスク (7ULL)
#define MIN_SPLIT_THRESHOLD   8ULL                // ブロック分割を行う最小データサイズ

#define BLOCK_FREE            1                   // ブロック状態: 空き
#define BLOCK_USED            0                   // ブロック状態: 使用中



// ====================================================================================
// ヒープブロックヘッダー構造体
// ====================================================================================
typedef struct HeapHeader {
  unsigned long long  size;     // データ領域のバイトサイズ (ヘッダー自体のサイズはのぞく)
  int                 is_free;  // 空き状態フラグ (1: 空き, 0: 使用中)
  struct HeapHeader   *next;    // 次のヒープブロックへのポインタ
} HeapHeader;

// ====================================================================================
// HeapAllocator: ヒープ管理構造体
// ====================================================================================
typedef struct {
  HeapHeader *start_block;      // 先頭ブロックへのポインタ
} HeapAllocator;

// ====================================================================================
// heap_init: ヒープ領域を初期化する
// ====================================================================================
// - 引数1 (heap):            初期化対象のヒープ構造体へのポインタ
// - 引数2 (allocator):       物理ページ割当用のフレームアロケータへのポインタ
// - 引数3 (initial_pages):   初期ヒープとして確保する 4KB ページ数
void heap_init(HeapAllocator *heap, BitmapFrameAllocator *allocator, unsigned long long initial_pages); 

// ====================================================================================
// kmalloc: 指定サイズの動的メモリ領域を確保する (malloc 相当)
// ====================================================================================
// - 引数1 (heap):            ヒープ構造体へのポインタ
// - 引数2 (size):            確保したいバイトサイズ
// - 戻り値:                  確保された領域の先頭アドレス (失敗時は 0)
void *kmalloc(HeapAllocator *heap, unsigned long long size);

// ====================================================================================
// kfree: 確保されたメモリ領域を解放する (free 相当)
// ====================================================================================
// - 引数1 (heap):            ヒープ構造体へのポインタ
// - 引数2 (ptr):             解放対象のアドレス (kmalloc の戻り値)
void kfree(HeapAllocator *heap, void *ptr);

#endif
