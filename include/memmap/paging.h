#ifndef PAGING_H
#define PAGING_H

#include "memory.h"

// ====================================================================================
// ページテーブルの概要と 48-bit 仮想アドレス空間の構造
// ====================================================================================
// [CPUのCR3レジスタ]
//        │
//        ▼
// 1. PML4  (Page Map Level 4)      ── 512GB 単位の大区切り
//        │
//        ▼
// 2. PDPT  (Page Directory Pointer) ── 1GB 単位の中区切り
//        │
//        ▼
// 3. PD    (Page Directory)        ── 2MB 単位の小区切り
//        │
//        ▼
// 4. PT    (Page Table)            ── 4KB 単位 (実際の物理アドレスを指す)
//        │
//        ▼
// [ 実際の物理 RAM アドレス ]
//
// x86_64 の 48-bit 仮想アドレス構造:
//
//  63         48 47     39 38     30 29     21 20     12 11        0
// +-------------+---------+---------+---------+---------+-----------+
// | (Sign Ext)  |  PML4   |  PDPT   |   PD    |   PT    |  Offset   |
// |  16-bits    | 9-bits  | 9-bits  | 9-bits  | 9-bits  |  12-bits  |
// +-------------+---------+---------+---------+---------+-----------+
//
//  - Bit 0 ~ 11  (12bit): 4KB ページ内のオフセット (2^12 = 4096 バイト)
//  - Bit 12 ~ 20  (9bit): Level 1 Page Table (PT) インデックス
//  - Bit 21 ~ 29  (9bit): Level 2 Page Directory (PD) インデックス
//  - Bit 30 ~ 38  (9bit): Level 3 Page Directory Pointer Table (PDPT) インデックス
//  - Bit 39 ~ 47  (9bit): Level 4 Page Map Level 4 (PML4) インデックス

// ====================================================================================
// ページテーブルエントリの属性フラグ定数定義
// ====================================================================================
#define PAGE_ENTRY_PRESENT      (1ULL << 0) // P    : ページが存在するか (1=有効)
#define PAGE_ENTRY_WRITABLE     (1ULL << 1) // R/W  : 読み書き許可 (1=書き込み許可)
#define PAGE_ENTRY_USER         (1ULL << 2) // U/S  : ユーザーモードアクセス可 (1=User)

#define PAGE_ENTRIES_PER_TABLE  512         // 1 つのテーブル内のエントリ数 (4KB / 8byte)

// ====================================================================================
// ページテーブル操作用マスク・シフト定数定義 
// ====================================================================================
#define PAGE_INDEX_MASK         0x1FFULL        // 9bit用インデックスマスク (0~511)
#define PAGE_ADDRESS_MASK       (~0xFFFULL)     // エントリから物理アドレス (4KB境界)

#define PML4_SHIFT              39              // Level 4 (PML4) ビットシフト数
#define PDPT_SHIFT              30              // Level 3 (PDPT) ビットシフト数
#define PD_SHIFT                21              // Level 2 (PD)   ビットシフト数
#define PT_SHIFT                12              // Level 1 (PT)   ビットシフト数

// ====================================================================================
// PageTable: ページテーブル構造体 (4KB 境界アライメント)
// ====================================================================================
// PML4, PDPT, PD, PT の全階層で共通して使用する 512 このエントリ配列
typedef struct {
  unsigned long long entries[PAGE_ENTRIES_PER_TABLE];
} PageTable;

// ====================================================================================
// setup_identity_mapping: 物理アドレスと仮想アドレスを 1 対 1 でマッピングする
// ====================================================================================
// - 引数1 (allocator):       ページテーブルメモリ確保用のフレームアロケータへのポインタ
// - 引数2 (max_phys_addr):   マッピング対象の最大物理アドレス (バイト単位)
// - 戻り値:                  作成された最頂点 PML4 テーブルの物理アドレス (0は失敗)
PageTable *setup_identity_mapping(BitmapFrameAllocator *allocator, unsigned long long max_phys_addr);

// ===============================================================================================
// load_pml4: 作成した PML4 テーブルのアドレスを CR3 レジスタに登録してページテーブルを有効化する
// ===============================================================================================
// - 引数1 (pml4_addr): PML4 テーブルの物理アドレス
void load_pml4(PageTable *pml4_addr);

#endif
