#ifndef MEMORY_H
#define MEMORY_H

#include "efi.h"

// ====================================================================================
// メモリ管理用の定数定義
// ====================================================================================
#define PAGE_SIZE     4096  // 1 ページ = 4KB (4096 バイト)
#define BITS_PER_BYTE 8     // 1 バイトあたりのビット数

// ページフレームの使用状態を示すフラグ定数
#define FRAME_FREE    0   // ページフレーム空き状態
#define FRAME_USED    1   // ページフレーム使用中状態
#define FRAME_ERROR   -1  // 範囲外アクセス等のエラー

// ====================================================================================
// BitmapFrameAllocator: ビットマップ方式の物理ページフレームアロケーター構造体
// ====================================================================================
typedef struct {
  unsigned char       *bitmap;      // ビットマップ配列の先頭物理アドレス (1bit = 1 ページ)
  unsigned long long  total_pages;  // 全物理ページ数
  unsigned long long  free_pages;   // 現在の空きページ数
} BitmapFrameAllocator;

// ====================================================================================
// frame_allocator_init: メモリマップをもとにフレームアロケータを初期化する
// ====================================================================================
// - 引数1 (allocator):   初期化対象ノアロケータ構造体へのポインタ
// - 引数2 (map):         取得済みの MemoryMap 構造体へのポインタ
void frame_allocator_init(BitmapFrameAllocator *allocator, MemoryMap *map);

// ====================================================================================
// alloc_frame: 1 ページ (4KB) の物理メモリを割り当てる
// ====================================================================================
// - 引数1 (allocator):   アロケータ構造体へのポインタ
// - 戻り値:              割り当てられた物理ページの先頭アドレス (失敗時は 0)
void *alloc_frame(BitmapFrameAllocator *allocator);

// ====================================================================================
// alloc_frames: 連続した複数ページ (4KB * count) の物理メモリを一括で割り当てる
// ====================================================================================
// - 引数1 (allocator):   アロケータ構造体へのポインタ
// - 引数2 (count):       確保したい連続ページ数
// - 戻り値:              割り当てられた物理ページの先頭アドレス (失敗時は 0)
void *alloc_frames(BitmapFrameAllocator *allocator, unsigned long long count);

// ====================================================================================
// free_frame: 指定した物理ページ (4KB) を解放する
// ====================================================================================
// - 引数1 (allocator):   アロケータ構造体へのポインタ
// - 引数2 (frame_addr):  解放する物理ページの先頭アドレス
void free_frame(BitmapFrameAllocator *allocator, void *frame_addr);
#endif
