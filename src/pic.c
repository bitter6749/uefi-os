#include "pic.h"
#include "io.h"

// ====================================================================================
// pic_remap: 8259A PIC の再配置と割り込みマスク設定
// ====================================================================================
void pic_remap(void) {
  // ----------------------------------------------------------------------------------
  // 1. ICW1: 初期化プロセスの開始
  // ----------------------------------------------------------------------------------
  // Master / Slave 両方の PIC に対し、初期化コマンド (ICW1) を送る
  outb(PIC_MASTER_CMD, ICW1_INIT | ICW1_ICW4);
  outb(PIC_SLAVE_CMD, ICW1_INIT | ICW1_ICW4);

  // ----------------------------------------------------------------------------------
  // 2. ICW2: 割り込みベクター番号のオフセット設定
  // ----------------------------------------------------------------------------------
  // デフォルトでは CPU 例外 (0~31) と衝突するため、ベクター番号を変更する
  outb(PIC_MASTER_DATA, PIC_MASTER_OFFSET); // IRQ0~7 -> Vector 32~39 (IRQ1 = 33)
  outb(PIC_SLAVE_DATA, PIC_SLAVE_OFFSET);   // IRQ8~15 -> Vector 40~47

  // ----------------------------------------------------------------------------------
  // 3. ICW3: Master / Slave の接続情報設定
  // ----------------------------------------------------------------------------------
  // Master 側の IRQ2 (Bit 2 = 0x04) に Slave PIC が接続されていることを指定
  outb(PIC_MASTER_DATA, 0x04);
  // Slave 側のカスケード ID (2) を指定
  outb(PIC_SLAVE_DATA, 0x02);

  // ----------------------------------------------------------------------------------
  // 4. ICW4: 動作モードの設定
  // ----------------------------------------------------------------------------------
  // 8086 モードで動作させるように指定
  outb(PIC_MASTER_DATA, ICW4_8086);
  outb(PIC_SLAVE_DATA, ICW4_8086);

  // ----------------------------------------------------------------------------------
  // 5. IMR (Interrupt Mask Register) の設定
  // ----------------------------------------------------------------------------------
  // キーボード (IRQ1) の割り込みを許可し、その他の不必要な IRQ ノイズを遮断
  outb(PIC_MASTER_DATA, PIC_MASK_IRQ1_ONLY);
  outb(PIC_SLAVE_DATA, PIC_MASK_ALL);
}

// ====================================================================================
// pic_disable: 8259A PIC の全割り込みマスク
// ====================================================================================
void pic_disable(void) {
  outb(PIC_MASTER_DATA, PIC_MASK_ALL);
  outb(PIC_SLAVE_DATA, PIC_MASK_ALL);
}














